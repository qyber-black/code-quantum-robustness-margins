function F = state_fidelity(chi, psi)
%STATE_FIDELITY State fidelity |<chi|psi>| of two normalised states.
%
%   Peer of python/src/qrobustness/states.py:state_fidelity.

    F = min(1, abs(chi(:)' * psi(:)));
end
