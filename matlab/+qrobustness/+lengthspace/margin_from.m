function m = margin_from(budget, speed)
%MARGIN_FROM budget/speed, with the zero-speed convention Inf.
%
%   Peer of python/src/qrobustness/lengthspace.py:margin_from.

    if speed > 0
        m = budget / speed;
    else
        m = Inf;
    end
end
