function b = angle_budget(F0, FT)
%ANGLE_BUDGET The angle budget acos(FT) - acos(F0) of the metric case.
%
%   Peer of python/src/qrobustness/lengthspace.py:angle_budget.

    b = acos(FT) - acos(min(F0, 1.0));
end
